namespace Friflo.WGSL.Transpiler.WGSL;


internal struct StructCode {
    public string source;
    public bool   alreadyDeclared;
}

public readonly struct CSharpType
{
    public readonly string      typeName;
    public readonly CsTypeCode  typeCode;

    public override string      ToString() => typeName;

    public CSharpType(string typeName, CsTypeCode typeCode) {
        this.typeName = typeName;
        this.typeCode = typeCode;
    }
}

public sealed class TypeEmitter
{
    private readonly    Dictionary<string, string>  structMap   = new();
    private readonly    List<StructCode>            fileStructs = [];
    private             WgslModule                  module;
    private             string                      fileNamespace;
    
    private static void DebugInputs(WgslFile[] wgslFiles, string projDir)
    {
        var path = Path.Combine(projDir, "debug.txt");
        var sb = new StringBuilder();
        sb.Append($"projDir: {projDir}\n\n");
        
        foreach (var file in wgslFiles) {
            sb.Append($"{file.NormalizedPath}\n");
        }
        File.WriteAllText(path, sb.ToString(), new UTF8Encoding(false));
    }
    
    private static string PathToNamespace(string path, string root = "")
    {
        var dir = Path.GetDirectoryName(path);
        if (string.IsNullOrEmpty(dir)) return root;

        var parts = dir.Split(['/', '\\', '-', '_'], StringSplitOptions.RemoveEmptyEntries);
        for (int i = 0; i < parts.Length; i++)
        {
            var p = parts[i];
            var rest = p.Length > 1 ? p.Substring(1) : "";
            parts[i] = (char.IsDigit(p[0]) ? "_" : "") + char.ToUpperInvariant(p[0]) + rest;
        }
        return $"{root}{string.Join(".", parts)}";
    }
    
    public void EmitAllStructs(WgslFile[] wgslFiles, string projDir)
    {
        for (int n = 0; n < wgslFiles.Length; n++) {
            var path =  wgslFiles[n].NormalizedPath.Substring(projDir.Length + 1);
            wgslFiles[n] = wgslFiles[n] with{ NormalizedPath =  path };
        }
        // DebugInputs(wgslFiles, projDir);
        
        // sort for deterministic generation
        WgslFile.Sort(wgslFiles);
        
        var sb = new StringBuilder();
        
        foreach (var file in wgslFiles)
        {
            var normalizedPath = file.NormalizedPath;
            try {
                // --- clear state first!
                sb.Clear();
                fileStructs.Clear();
                fileNamespace = PathToNamespace(normalizedPath);
                
                // --- process after
                module = WgslParser.ParseWgsl(file.Content, normalizedPath);
                
                EmitModule();
                
                if (fileStructs.Count == 0) {
                    continue;
                }
                sb.Append("// <auto-generated />\n");
                sb.Append("using System;\n");
                sb.Append("using System.Numerics;\n");
                sb.Append("using Friflo.Vectorization.WebGPU;\n");
                sb.Append("\n");
                // sb.Append("// ReSharper disable CheckNamespace\n");
                // sb.Append("// ReSharper disable InconsistentNaming\n");
                sb.Append($"namespace {fileNamespace};\n");
                sb.Append("\n\n");
                foreach (var structSource in fileStructs) {
                    if (!structSource.alreadyDeclared) {
                        sb.Append($"[Source(\"~/{normalizedPath}\")]\n");
                    } 
                    sb.Append(structSource.source);
                }
            }
            catch (Exception exception) {
                sb.Append($"/* -------- Error parsing: {normalizedPath}\n");
                sb.Append(WgslUtils.GetExceptionAsString(exception));
                sb.Append("\n*/\n");
            }
            var source =  sb.ToString();
            var path = $"{projDir}/{file.NormalizedPath}.cs";

            File.WriteAllText(path, source, new UTF8Encoding(false));
        }
    }
        
    private void EmitModule()
    {
        var structs = module.Structs;
        var bindings = module.Bindings;
        if (bindings.Count == 0 || structs.Count == 0) {
            return;
        }
        foreach (var binding in bindings)
        {
            var typeName = binding.WgslType.Name;
            var wgslStruct = structs.FirstOrDefault(s => s.Name == typeName);
            if (wgslStruct == null) continue;
            AddStruct(wgslStruct);
        }
    }
    
    private void AddStruct(WgslStruct wgslStruct)
    {
        var sb = new StringBuilder();
        sb.Clear();
        sb.Append($"public struct {wgslStruct.Name} (\n");
        foreach (var field in wgslStruct.Fields) {
            var csharpType = GetCSharpType(field.WgslType);
            sb.Append($"    {csharpType.typeName} {field.Name},\n");
        }
        sb.Length -= 2;
        sb.Append(")\n");
        sb.Append("{\n");
        foreach (var field in wgslStruct.Fields) {
            var csharpType = GetCSharpType(field.WgslType);
            sb.Append($"    public {csharpType} {field.Name} = {field.Name};\n");
        }
        sb.Append("}\n\n");
        var source          = sb.ToString();
        var alreadyDeclared = false;
        var fullQualifiedName   = $"{fileNamespace}-{wgslStruct.Name}";
        
        if (structMap.TryGetValue(fullQualifiedName, out var curSource)) {
            if (source == curSource) {
                source = $"/// Skipped identical duplicate of  <see cref=\"{wgslStruct.Name}\"/>\nfile partial class _info;\n\n";
                alreadyDeclared = true;
            }
        } else {
            structMap.Add(fullQualifiedName, source);
        }
        fileStructs.Add(new StructCode { source = source, alreadyDeclared = alreadyDeclared });
    }
    
    private CSharpType GetCSharpType(WgslType type)
    {
        var generics = type.Generics;
        var arg_0 = generics.Length > 0 ? generics[0].Name : "";
        
        return GetType(type.Name, arg_0);
    }

    
    private static readonly  CSharpType[]                   TypeCodeMap;
    private static readonly  Dictionary<string,CSharpType>  WgslTypeMap = new();
    
    private static void MapType(CSharpType[] typeCodeMap, Dictionary<string, CSharpType> wgslTypeMap, CsTypeCode code, string typeName) {
        typeCodeMap[(int)code]       = new CSharpType(typeName, code);
        wgslTypeMap[code.ToString()] = new CSharpType(typeName, code);
    }
    
    static TypeEmitter()
    {
        const int length = (int)CsTypeCode.WgslStruct;
        var tcMap   = TypeCodeMap = new CSharpType[length];
        var wgslMap = WgslTypeMap;
        var values  = Enum.GetValues(typeof(CsTypeCode)).Cast<CsTypeCode>();
        
        foreach (var value in values) {
            if ((int)value >= length) continue;
            MapType(tcMap, wgslMap, value, value.ToString());
        }
        MapType(tcMap, wgslMap, CsTypeCode.f16,     "Half");
        MapType(tcMap, wgslMap, CsTypeCode.f32,     "float");
        MapType(tcMap, wgslMap, CsTypeCode.i32,     "int");
        MapType(tcMap, wgslMap, CsTypeCode.u32,     "uint");
        
        MapType(tcMap, wgslMap, CsTypeCode.vec2f,   "Vector2");
        MapType(tcMap, wgslMap, CsTypeCode.vec3f,   "Vector3");
        MapType(tcMap, wgslMap, CsTypeCode.vec4f,   "Vector4");
        
        MapType(tcMap, wgslMap, CsTypeCode.mat4x4f, "Matrix4x4");
        MapType(tcMap, wgslMap, CsTypeCode.mat3x2f, "Matrix3x2");
    }
    
    private static CSharpType FromCode(CsTypeCode code, int offset) => TypeCodeMap[(int)code + offset];

    private static readonly CSharpType InvalidType = new CSharpType("invalid_type", CsTypeCode.None);
    
    private static CSharpType GetVec(string primitive, CsTypeCode code)
    {
        return primitive switch
        {
            "f16"   => FromCode(code, 0),
            "f32"   => FromCode(code, 1),
            "i32"   => FromCode(code, 2),
            "u32"   => FromCode(code, 3),
            _       => InvalidType
        };
    }
    
    private static CSharpType GetMat(string primitive, int w, int h)
    {
        var code = (w, h) switch
        {
            (2, 2)  => CsTypeCode.mat2x2h,
            (2, 3)  => CsTypeCode.mat2x3h,
            (2, 4)  => CsTypeCode.mat2x4h,
            //
            (3, 2)  => CsTypeCode.mat3x2h,
            (3, 3)  => CsTypeCode.mat3x3h,
            (3, 4)  => CsTypeCode.mat3x4h,
            //
            (4, 2)  => CsTypeCode.mat4x2h,
            (4, 3)  => CsTypeCode.mat4x3h,
            (4, 4)  => CsTypeCode.mat4x4h,
            //
            _       => CsTypeCode.None,
        };
        if (code == CsTypeCode.None) throw new InvalidOperationException();
        
        return primitive switch
        {
            "f16"   => FromCode(code, 0),
            "f32"   => FromCode(code, 1),
            _       => InvalidType
        };
    }

    private CSharpType GetType(string typeName, string arg_0)
    {
        switch (typeName)
        {
            case "array":   return GetType  (arg_0, null);
            //
            case "vec2":    return GetVec(arg_0, CsTypeCode.vec2h);
            case "vec3":    return GetVec(arg_0, CsTypeCode.vec3h);
            case "vec4":    return GetVec(arg_0, CsTypeCode.vec4h);
            //
            case "mat2x2":  return GetMat(arg_0, 2, 2);
            case "mat2x3":  return GetMat(arg_0, 2, 3);
            case "mat2x4":  return GetMat(arg_0, 2, 4);
            //
            case "mat3x2":  return GetMat(arg_0, 3, 2);
            case "mat3x3":  return GetMat(arg_0, 3, 3);
            case "mat3x4":  return GetMat(arg_0, 3, 4);
            //
            case "mat4x2":  return GetMat(arg_0, 4, 2);
            case "mat4x3":  return GetMat(arg_0, 4, 3);
            case "mat4x4":  return GetMat(arg_0, 4, 4);
        }
        if (WgslTypeMap.TryGetValue(typeName, out var csharp)) {
            return csharp;
        }
        var wgslStruct = module.Structs.FirstOrDefault(s => s.Name == typeName);
        if (wgslStruct != null) {
            AddStruct(wgslStruct);
        }
        return new CSharpType(typeName, CsTypeCode.WgslStruct);
    }
}